'use client'

import { themeRootAttrs, themeToCss } from '@commerce/core/theme'
import { cn } from '@commerce/ui/lib/utils'
import type { ReactNode } from 'react'
import { useCustomizePuck } from '@/lib/customize-puck'
import { useThemePreview } from '@/lib/customize-theme-context'
import SectionPreview from './section-preview'

type SectionLivePreviewProps = { type: string; className?: string }

/** Same selector the scoped theme CSS is written under, so it never touches admin's own `:root` tokens. */
const SELECTOR = '[data-section-live-preview]'
/** The content column a section actually renders at; the wrapper scales it down to fit the preview box. */
const CONTENT_WIDTH = 1200
const SCALE = 0.17

/**
 * A live render of a section with its default props, scaled down and scoped to the
 * theme being edited — Shopify's hover preview, not a static icon. Falls back to the
 * schematic glyph when the theme isn't available yet or the section can't be rendered
 * standalone (storefront CSS classes leaking into admin's own chrome is the failure
 * mode this guards against by scoping every custom property under `SELECTOR`).
 */
export default function SectionLivePreview({ type, className }: SectionLivePreviewProps) {
  // Hooks
  const theme = useThemePreview()
  const components = useCustomizePuck((s) => s.config.components)

  // Early returns
  const component = components[type]
  let content: ReactNode = null
  if (component?.render) {
    try {
      content = component.render(component.defaultProps as never)
    } catch {
      content = null
    }
  }
  if (!theme || !content) return <SectionPreview type={type} className={className} />

  // Render logic
  const css = themeToCss(theme).replaceAll(':root', SELECTOR)
  const rootAttrs = themeRootAttrs(theme)

  return (
    <div
      className={cn(
        'relative overflow-hidden rounded-md border border-border bg-background',
        className,
      )}
    >
      {/* biome-ignore lint/security/noDangerouslySetInnerHtml: theme CSS text generated by themeToCss, not user input. */}
      <style dangerouslySetInnerHTML={{ __html: css }} />
      <div
        data-section-live-preview
        data-theme="light"
        {...rootAttrs}
        className="pointer-events-none absolute top-0 left-0 origin-top-left"
        style={{ width: CONTENT_WIDTH, transform: `scale(${SCALE})` }}
      >
        {content}
      </div>
    </div>
  )
}
