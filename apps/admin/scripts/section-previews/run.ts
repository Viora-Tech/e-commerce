/**
 * `bun run section-previews` (apps/admin): the Add panel's section pictures.
 *
 * Draws every addable section with its default settings and the default theme (./entry.tsx,
 * bundled with Bun, styled with the storefront's own Tailwind build), photographs each one in a
 * local Chrome through puppeteer-core (Apache-2.0, a dev dependency; no browser is downloaded),
 * and writes `public/section-previews/<Type>.webp` and `<Type>-dark.webp`, each at most 40 KB,
 * plus `src/lib/section-previews.ts`, the list the admin reads. Run it after adding a section
 * or changing how one looks, and commit what it writes.
 *
 * Chrome: `CHROME_PATH`, else the usual install location for this OS. `--serve` only serves the
 * page of sections (add `?mode=dark`) to look at in a browser, without taking pictures.
 */
import { existsSync } from 'node:fs'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { defaultTheme, THEME_FONTS } from '@commerce/core/theme'
import tailwind from '@tailwindcss/postcss'
import postcss from 'postcss'
import puppeteer from 'puppeteer-core'

const ADMIN = resolve(import.meta.dir, '../..')
const STOREFRONT_CSS = resolve(ADMIN, '../storefront/src/app/globals.css')
const OUT_DIR = join(ADMIN, 'public/section-previews')
const LIST_FILE = join(ADMIN, 'src/lib/section-previews.ts')

/** Sections are drawn at a desktop content width, then scaled to this many pixels wide. */
const PAGE_WIDTH = 1280
const IMAGE_WIDTH = 512
/** Taller sections are cut at 3:4 of their width; the tile and hover card show the top. */
const MAX_HEIGHT = Math.round(PAGE_WIDTH * 0.75)
const MAX_BYTES = 40 * 1024
/**
 * A picture this small is a blank band: a section that needs a store to show anything (a
 * scroll-driven reveal, reviews, an empty rich text). Those keep their drawn glyph instead.
 */
const MIN_BYTES = 900
const QUALITIES = [72, 60, 48, 36]

const CHROME_PATHS = [
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
]

function chromePath(): string {
  const found = [process.env.CHROME_PATH, ...CHROME_PATHS].find((p) => p && existsSync(p))
  if (!found) throw new Error('Chrome not found. Set CHROME_PATH to a Chrome or Chromium binary.')
  return found
}

async function storefrontCss(): Promise<string> {
  const source = await readFile(STOREFRONT_CSS, 'utf8')
  const result = await postcss([tailwind()]).process(source, { from: STOREFRONT_CSS })
  return result.css
}

async function bundle(): Promise<string> {
  const built = await Bun.build({
    entrypoints: [join(import.meta.dir, 'entry.tsx')],
    target: 'browser',
    minify: true,
    define: { 'process.env.NODE_ENV': '"production"' },
  })
  if (!built.success) throw new AggregateError(built.logs, 'Bundling the sections failed')
  const [output] = built.outputs
  if (!output) throw new Error('Bundling the sections produced nothing')
  return output.text()
}

function page(css: string): string {
  const { heading, body } = defaultTheme.fonts
  const families = [...new Set([heading, body])].map((id) => `family=${THEME_FONTS[id].google}`)
  const fonts = `https://fonts.googleapis.com/css2?${families.join('&')}&display=block`
  return `<!doctype html><html lang="en"><head><meta charset="utf-8">
<link rel="stylesheet" href="${fonts}"><style>${css}</style>
<style>body{margin:0;background:var(--color-bg)}#previews{width:${PAGE_WIDTH}px}</style>
</head><body><div id="previews"></div><script type="module" src="/entry.js"></script></body></html>`
}

/** The generated list the admin imports: which types have pictures, and each one's shape. */
function listFile(shapes: Record<string, number>): string {
  const rows = Object.entries(shapes)
    .sort(([a], [b]) => a.localeCompare(b))
    // Keys unquoted where they can be, as biome writes them.
    .map(
      ([type, ratio]) =>
        `  ${/^[A-Za-z_$][\w$]*$/.test(type) ? type : JSON.stringify(type)}: ${ratio},`,
    )
  return `/**
 * GENERATED by \`bun run section-previews\` (apps/admin/scripts/section-previews). Do not edit.
 * Section types with a picture in \`public/section-previews\` (light \`<Type>.webp\`, dark
 * \`<Type>-dark.webp\`), each with its height as a fraction of its width.
 */
export const SECTION_PREVIEWS: Record<string, number> = {
${rows.join('\n')}
}
`
}

async function main() {
  const [css, script] = await Promise.all([storefrontCss(), bundle()])
  const html = page(css)
  const server = Bun.serve({
    port: 0,
    fetch(req) {
      const { pathname } = new URL(req.url)
      if (pathname === '/entry.js') {
        return new Response(script, { headers: { 'content-type': 'text/javascript' } })
      }
      return new Response(html, { headers: { 'content-type': 'text/html' } })
    },
  })
  if (process.argv.includes('--serve')) {
    // Look at every section as the script draws it (add ?mode=dark), without taking pictures.
    console.log(`Sections page: ${server.url}  (Ctrl+C to stop)`)
    return
  }
  const browser = await puppeteer.launch({ executablePath: chromePath(), headless: true })
  const shapes: Record<string, number> = {}
  const darkDone = new Set<string>()
  try {
    await rm(OUT_DIR, { recursive: true, force: true })
    await mkdir(OUT_DIR, { recursive: true })
    for (const mode of ['light', 'dark'] as const) {
      const tab = await browser.newPage()
      await tab.setViewport({
        width: PAGE_WIDTH,
        height: 900,
        deviceScaleFactor: IMAGE_WIDTH / PAGE_WIDTH,
      })
      // Reveal and marquee motion settle at their end state, so nothing is caught mid-fade.
      await tab.emulateMediaFeatures([
        { name: 'prefers-reduced-motion', value: 'reduce' },
        { name: 'prefers-color-scheme', value: mode },
      ])
      await tab.goto(`${server.url}?mode=${mode}`, { waitUntil: 'networkidle0' })
      await tab.waitForFunction(() => Array.isArray(window.__previews), { timeout: 60_000 })
      const types = await tab.evaluate(() => window.__previews ?? [])
      for (const type of types) {
        const box = await tab.$eval(`[data-preview="${type}"]`, (el) => {
          const r = el.getBoundingClientRect()
          return { x: r.left + scrollX, y: r.top + scrollY, height: r.height }
        })
        const height = Math.min(Math.ceil(box.height), MAX_HEIGHT)
        let bytes: Uint8Array | null = null
        for (const quality of QUALITIES) {
          bytes = await tab.screenshot({
            type: 'webp',
            quality,
            captureBeyondViewport: true,
            clip: { x: 0, y: box.y, width: PAGE_WIDTH, height },
          })
          if (bytes.byteLength <= MAX_BYTES) break
        }
        if (!bytes || bytes.byteLength > MAX_BYTES) {
          console.warn(`${type} (${mode}): over 40 KB at every quality, left out`)
          continue
        }
        if (mode === 'light' && bytes.byteLength < MIN_BYTES) {
          console.log(`${type}: draws nothing without a store, keeps its glyph`)
          continue
        }
        if (mode === 'dark' && !(type in shapes)) continue
        const name = mode === 'light' ? `${type}.webp` : `${type}-dark.webp`
        await writeFile(join(OUT_DIR, name), bytes)
        if (mode === 'light') shapes[type] = Math.round((height / PAGE_WIDTH) * 1000) / 1000
        else darkDone.add(type)
      }
      console.log(`${mode}: ${types.length} sections`)
      await tab.close()
    }
    // A type is listed only with both pictures, so the admin never asks for a missing file.
    const both = Object.fromEntries(Object.entries(shapes).filter(([t]) => darkDone.has(t)))
    await writeFile(LIST_FILE, listFile(both))
  } finally {
    await browser.close()
    server.stop(true)
  }
}

await main()
