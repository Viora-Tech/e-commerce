/**
 * SPIKE stress test: lists every `'use client'` module in apps/admin/src as a lazy import, so
 * `LAB_STRESS=1 bun run build` bundles the admin's whole client side (about what a full port
 * would ship) and the build's memory can be measured. Output is gitignored.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const src = join(import.meta.dir, '../../admin/src')
const files: string[] = []
function walk(dir: string) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.tsx?$/.test(name) && !/\.test\.tsx?$/.test(name)) {
      if (/^['"]use client['"]/.test(readFileSync(p, 'utf8'))) files.push(p)
    }
  }
}
walk(src)
const lines = files.map(
  (f) =>
    `  () => import('@/${relative(src, f)
      .split(sep)
      .join('/')
      .replace(/\.tsx?$/, '')}'),`,
)
writeFileSync(
  join(import.meta.dir, '../src/stress-all.gen.ts'),
  `// Generated by stress/gen.ts (${files.length} modules).\nexport const all = [\n${lines.join('\n')}\n]\n`,
)
console.log(`${files.length} client modules`)
