/**
 * Writes `packages/core/src/apps/catalogue.generated.ts`: the public App Store catalogue, one
 * entry per plugin in `commerce.config.ts` that has a `listing` (and is not `unlisted`). The App
 * Store site (apps/www) cannot import the plugins (they carry server code), so the parts it
 * shows are copied out here, from the same manifests the admin reads.
 *
 *   bun scripts/gen-app-catalogue.ts
 *
 * The `app-catalogue` sweep fails when the file is out of date with the manifests.
 */
import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import type { PluginManifest } from '@commerce/plugins'
import type { CatalogueEntry } from '../packages/core/src/apps/catalogue'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const CATALOGUE_FILE = path.join(ROOT, 'packages/core/src/apps/catalogue.generated.ts')

/** The listed apps, in config order. Throws when a listed app is missing a category. */
export function collectCatalogue(plugins: PluginManifest[]): CatalogueEntry[] {
  return plugins.flatMap((p): CatalogueEntry[] => {
    const listing = p.listing
    if (!listing || listing.unlisted) return []
    if (!p.category) throw new Error(`${p.id}: a listed app needs a category`)
    return [
      {
        id: p.id,
        name: p.name,
        kind: p.kind,
        category: p.category,
        company: p.kind === 'connection' ? (p.company ?? null) : null,
        description: p.description ?? listing.tagline,
        tagline: listing.tagline,
        highlights: listing.highlights,
        guide: listing.guide ?? null,
        worksWith: listing.worksWith ?? [],
        screenshots: listing.screenshots ?? [],
        keywords: listing.keywords ?? [],
        access: {
          resources: p.access.resources.map((r) => ({
            resource: r.resource,
            level: r.level,
            why: r.why,
          })),
          shares: (p.access.shares ?? []).map((s) => ({ when: s.when, what: s.what })),
        },
        adminPages: (p.admin?.pages ?? []).flatMap((page) =>
          page.navLabel ? [page.navLabel] : [],
        ),
        themeBlocks: (p.storefront?.blocks ?? []).map((b) => b.label),
        credits: (p.credits ?? []).map((c) => ({ name: c.name, url: c.url, license: c.license })),
      },
    ]
  })
}

function render(entries: CatalogueEntry[]): string {
  return `/** SOURCE OF TRUTH: generated App Store catalogue — WHAT: the listed apps, copied from the plugin manifests / WHY: the App Store site cannot import the plugins. Generated by \`bun scripts/gen-app-catalogue.ts\`. Do not edit. */
import type { CatalogueEntry } from './catalogue'

export const APP_CATALOGUE_DATA: CatalogueEntry[] = ${JSON.stringify(entries, null, 2)}
`
}

if (import.meta.main) {
  const config = (await import('../commerce.config')).default
  writeFileSync(CATALOGUE_FILE, render(collectCatalogue(config.plugins)))
  spawnSync('bunx', ['biome', 'format', '--write', CATALOGUE_FILE], {
    cwd: ROOT,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  })
}
