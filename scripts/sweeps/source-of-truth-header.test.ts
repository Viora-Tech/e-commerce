describe('sweep: source-of-truth-header', () => {
  it('new files under packages/core/src and packages/plugins/src have a SOURCE OF TRUTH header', async () => {
    const files = await listFiles(SCOPE_ROOTS, { includeTests: true })
    const missing: string[] = []
    for (const f of files) {
      const rel = toRel(f)
      if (EXISTING_FILES.has(rel)) continue
      const text = readFileSync(f, 'utf8')
      if (!HEADER_RE.test(text)) missing.push(rel)
    }
    expect(
      missing,
      `new file(s) missing a "/** SOURCE OF TRUTH: ... */" header (see docs/guardrails.md):\n${missing.join('\n')}`,
    ).toEqual([])
  })
})
