/**
 * Builds the storefront's section stylesheet module: the blocks section styles that only our own
 * themes' sections use (`packages/blocks/src/styles/sections.css`), minified the way Next builds
 * the global stylesheet (lightningcss, the same browser targets), into
 * `apps/storefront/src/lib/section-styles.generated.ts`. The storefront serves it at
 * `/api/section-styles` (`lib/section-styles.ts`).
 *
 * Run after changing any file sections.css lists: `bun run css:sections`. The storefront test
 * `section-styles.test.ts` fails while the module is out of date.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { transform } from 'lightningcss'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const stylesDir = join(root, 'packages/blocks/src/styles')
const out = join(root, 'apps/storefront/src/lib/section-styles.generated.ts')

/** The files sections.css imports, in order. */
export function sectionFiles() {
  const list = readFileSync(join(stylesDir, 'sections.css'), 'utf8')
  return [...list.matchAll(/@import "\.\/([^"]+\.css)";/g)].map((m) => m[1])
}

/** Every listed file's source, in order (the hash the test compares). */
export function sourceHash() {
  const hash = createHash('sha256')
  for (const file of sectionFiles())
    hash.update(`${file}\n`).update(readFileSync(join(stylesDir, file)))
  return hash.digest('hex').slice(0, 16)
}

// Next's default browser targets (chrome/edge/firefox 111, safari 16.4), as lightningcss numbers.
const v = (major, minor = 0) => (major << 16) | (minor << 8)
const targets = { chrome: v(111), edge: v(111), firefox: v(111), safari: v(16, 4) }

function build() {
  const source = sectionFiles()
    .map((file) => readFileSync(join(stylesDir, file), 'utf8'))
    .join('\n')
  const { code } = transform({
    filename: 'sections.css',
    code: Buffer.from(source),
    minify: true,
    targets,
  })
  const css = code.toString()
  const version = createHash('sha256').update(css).digest('hex').slice(0, 12)
  const body = `/**
 * Generated by \`scripts/storefront-css/sections-css.mjs\` (\`bun run css:sections\`); do not edit.
 * The blocks section styles only our own themes' sections use
 * (\`packages/blocks/src/styles/sections.css\`), minified, served at \`/api/section-styles\`.
 */
export const SECTION_STYLES_SOURCE_HASH = '${sourceHash()}'
export const SECTION_STYLES_VERSION = '${version}'
export const SECTION_STYLES_CSS =
  ${JSON.stringify(css)}
`
  writeFileSync(out, body)
  console.log(`section styles: ${sectionFiles().length} files, ${css.length} bytes, v=${version}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build()
